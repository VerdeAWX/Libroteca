CREATE DATABASE IF NOT EXISTS biblioteca CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE biblioteca;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL, rut VARCHAR(15) NOT NULL UNIQUE,
 correo VARCHAR(150) NOT NULL UNIQUE, `contraseña` VARCHAR(255) NOT NULL,
 rol ENUM('bibliotecario','estudiante') NOT NULL
);
CREATE TABLE IF NOT EXISTS estudiantes (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL, rut VARCHAR(15) NOT NULL UNIQUE,
 curso VARCHAR(50) NOT NULL, correo VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS categorias (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS libros (
 id INT AUTO_INCREMENT PRIMARY KEY, titulo VARCHAR(200) NOT NULL, autor VARCHAR(150) NOT NULL,
 isbn VARCHAR(20) NOT NULL UNIQUE, editorial VARCHAR(120) NOT NULL, stock INT NOT NULL DEFAULT 0,
 id_categoria INT NOT NULL, CONSTRAINT fk_libro_categoria FOREIGN KEY(id_categoria) REFERENCES categorias(id)
);
CREATE TABLE IF NOT EXISTS prestamos (
 id INT AUTO_INCREMENT PRIMARY KEY, id_estudiante INT NOT NULL, id_libro INT NOT NULL,
 fecha_prestamo DATE NOT NULL, fecha_devolucion DATE NOT NULL, devuelto BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT fk_prestamo_estudiante FOREIGN KEY(id_estudiante) REFERENCES estudiantes(id),
 CONSTRAINT fk_prestamo_libro FOREIGN KEY(id_libro) REFERENCES libros(id)
);
